-- Esquema da plataforma de feedback (PostgreSQL)
-- Aplicar uma única vez no banco "feedback" (psql ou Query editor do portal).

CREATE TABLE IF NOT EXISTS avaliacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao   VARCHAR(1000) NOT NULL,
    nota        INTEGER       NOT NULL CHECK (nota BETWEEN 0 AND 10),
    urgencia    VARCHAR(10)   NOT NULL CHECK (urgencia IN ('CRITICA', 'MEDIA', 'BAIXA')),
    data_envio  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Relatório semanal filtra por período
CREATE INDEX IF NOT EXISTS idx_avaliacao_data_envio ON avaliacao (data_envio);
